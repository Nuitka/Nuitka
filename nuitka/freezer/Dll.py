"""For standalone shared library ('--mode=dll') host binding creation."""

import os

from nuitka.__past__ import unicode
from nuitka.options.Options import DLL_HEADER_LANGUAGES, getDllHeaderLanguages
from nuitka.OutputDirectories import (
    getDllBasename,
    getDllHeaderBasePath,
    getStandaloneDirectoryFolderName,
)
from nuitka.utils.CStrings import encodePythonStringToC, encodePythonUnicodeToC
from nuitka.utils.FileOperations import putTextFileContents


def _toUnicode(value):
    if type(value) is unicode:
        return value

    return value.decode("utf8")


def _encodeCStringLiteral(value):
    return encodePythonStringToC(_toUnicode(value).encode("utf8"))


def _encodeCWideStringLiteral(value):
    return encodePythonUnicodeToC(_toUnicode(value))


def _encodeRustStringLiteral(value):
    escaped = (
        _toUnicode(value)
        .replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return '"%s"' % escaped


def _getOtherDllHeaderLanguagesComment(language):
    other_languages = [
        candidate for candidate in DLL_HEADER_LANGUAGES if candidate != language
    ]
    if other_languages:
        return (
            "Other host binding languages available via '--dll-header-language': %s."
            % ", ".join(other_languages)
        )

    return "No other host binding languages are currently available."


def _createDllCHeaderFile(base_path, dist_dir_name, dll_basename, relative_dll_path):
    contents = """\
// Generated by Nuitka for '--mode=dll'.
// Compatible with C (C99+), C++, and Zig ('@cImport').
// %(other_bindings)s

#ifndef NUITKA_DLL_HEADER_INCLUDED
#define NUITKA_DLL_HEADER_INCLUDED

#if !defined(__cplusplus)
#include <stdbool.h>
#endif
#if defined(_WIN32)
#include <wchar.h>
#endif

#ifdef __cplusplus
extern "C" {
#endif

#if defined(_WIN32)
typedef wchar_t nuitka_dll_char_t;
#define NUITKA_DLL_API __declspec(dllimport)
#else
typedef char nuitka_dll_char_t;
#define NUITKA_DLL_API
#endif

typedef int (*nuitka_dll_run_code_fn)(
    int argc,
    nuitka_dll_char_t **argv,
    nuitka_dll_char_t const *dll_filename,
    bool fork_only
);

NUITKA_DLL_API int run_code(
    int argc,
    nuitka_dll_char_t **argv,
    nuitka_dll_char_t const *dll_filename,
    bool fork_only
);

#ifdef __cplusplus
}
#endif

#endif

#undef NUITKA_DLL_DIST_DIR
#undef NUITKA_DLL_FILENAME
#undef NUITKA_DLL_RELATIVE_PATH
#if defined(_WIN32)
#define NUITKA_DLL_DIST_DIR %(wide_dist_dir)s
#define NUITKA_DLL_FILENAME %(wide_dll_filename)s
#define NUITKA_DLL_RELATIVE_PATH %(wide_relative_path)s
#else
#define NUITKA_DLL_DIST_DIR %(narrow_dist_dir)s
#define NUITKA_DLL_FILENAME %(narrow_dll_filename)s
#define NUITKA_DLL_RELATIVE_PATH %(narrow_relative_path)s
#endif
""" % {
        "other_bindings": _getOtherDllHeaderLanguagesComment("c"),
        "wide_dist_dir": _encodeCWideStringLiteral(dist_dir_name),
        "wide_dll_filename": _encodeCWideStringLiteral(dll_basename),
        "wide_relative_path": _encodeCWideStringLiteral(relative_dll_path),
        "narrow_dist_dir": _encodeCStringLiteral(dist_dir_name),
        "narrow_dll_filename": _encodeCStringLiteral(dll_basename),
        "narrow_relative_path": _encodeCStringLiteral(relative_dll_path),
    }

    putTextFileContents(base_path + ".h", contents, encoding="utf-8")


def _createDllRustHeaderFile(base_path, dist_dir_name, dll_basename, relative_dll_path):
    contents = """\
// Generated by Nuitka for '--mode=dll'.
// %(other_bindings)s

#[cfg(windows)]
#[allow(dead_code)]
pub type NuitkaDllChar = u16;

#[cfg(not(windows))]
#[allow(dead_code)]
pub type NuitkaDllChar = std::os::raw::c_char;

#[allow(dead_code)]
pub type NuitkaDllRunCodeFn = unsafe extern "C" fn(
    argc: std::os::raw::c_int,
    argv: *mut *mut NuitkaDllChar,
    dll_filename: *const NuitkaDllChar,
    fork_only: bool,
) -> std::os::raw::c_int;

#[allow(dead_code)]
pub const NUITKA_DLL_SYMBOL_NAME: &[u8] = b"run_code\\0";

#[allow(dead_code)]
pub const NUITKA_DLL_DIST_DIR: &str = %(dist_dir)s;

#[allow(dead_code)]
pub const NUITKA_DLL_FILENAME: &str = %(dll_filename)s;

#[allow(dead_code)]
pub const NUITKA_DLL_RELATIVE_PATH: &str = %(relative_path)s;
""" % {
        "other_bindings": _toUnicode(_getOtherDllHeaderLanguagesComment("rust")),
        "dist_dir": _encodeRustStringLiteral(dist_dir_name),
        "dll_filename": _encodeRustStringLiteral(dll_basename),
        "relative_path": _encodeRustStringLiteral(relative_dll_path),
    }

    putTextFileContents(base_path + ".rs", contents, encoding="utf-8")


def createDllHeaderFiles():
    languages = getDllHeaderLanguages()
    if not languages:
        return

    base_path = getDllHeaderBasePath()
    dist_dir_name = getStandaloneDirectoryFolderName(bundle=False)
    dll_basename = getDllBasename()
    relative_dll_path = os.path.join(dist_dir_name, dll_basename)

    for language in languages:
        if language == "c":
            _createDllCHeaderFile(
                base_path=base_path,
                dist_dir_name=dist_dir_name,
                dll_basename=dll_basename,
                relative_dll_path=relative_dll_path,
            )
        elif language == "rust":
            _createDllRustHeaderFile(
                base_path=base_path,
                dist_dir_name=dist_dir_name,
                dll_basename=dll_basename,
                relative_dll_path=relative_dll_path,
            )
        else:
            assert False, language


